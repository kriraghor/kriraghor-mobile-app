/** Every path of one weight of an icon, joined into one drawing. */
async function drawing(icon, weight) {
  const mod = await import(pathToFileURL(resolve(source, 'dist', 'defs', `${icon}.mjs`)).href);
  const node = mod.default.get(weight);
  if (!node) throw new Error(`${icon} has no ${weight} weight`);
  const out = [];
  const walk = (el) => {
    if (!el || typeof el !== 'object') return;
    if (Array.isArray(el)) return el.forEach(walk);
    if (el.type === 'path') {
      if (el.props.opacity) throw new Error(`${icon} ${weight}: a faded path cannot be merged`);
      out.push(el.props.d);
    } else if (typeof el.type === 'string') {
      throw new Error(`${icon} ${weight}: <${el.type}> is not a path`);
    }
    walk(el.props?.children);
  };
  walk(node);
  if (!out.length) throw new Error(`${icon} ${weight}: no path`);
  return out.join('');
}

const lines = [];
for (const [name, [icon, solid]] of Object.entries(MAP)) {
  const r = await drawing(icon, 'regular');
  const f = solid ? await drawing(icon, 'fill') : null;
  const key = /^[a-z][a-z0-9]*$/.test(name) ? name : JSON.stringify(name);
  lines.push(`  ${key}: { r: ${JSON.stringify(r)}${f ? `, f: ${JSON.stringify(f)}` : ''} },`);
}

const file = `// Generated by scripts/build-glyphs.mjs from Phosphor Icons (MIT, phosphoricons.com). Do not edit by hand.
// The websites use the same family, so the app and the web show the same drawings. 256 grid, drawn as
// filled shapes: \`r\` is the outline ("regular"), \`f\` the solid one, shown when the icon is selected.
export type Glyph = { readonly r: string; readonly f?: string };

/** The grid every drawing is made on. */
export const GLYPH_GRID = 256;

export const GLYPHS = {
${lines.join('\n')}
} as const satisfies Record<string, Glyph>;

export type IconName = keyof typeof GLYPHS;
`;
