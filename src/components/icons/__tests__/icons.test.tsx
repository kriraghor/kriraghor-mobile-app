import { create, act } from 'react-test-renderer';
import { GLYPH_GRID, GLYPHS, type Glyph, type IconName } from '../glyphs';
import { Icon } from '../Icon';

const NAMES = Object.keys(GLYPHS) as IconName[];
const glyph = (n: IconName): Glyph => GLYPHS[n];
const DRAWING = /^M[\d\s.,MmLlHhVvCcSsQqTtAaZz-]+$/;

describe('the app icon set (Phosphor drawings, generated by scripts/build-glyphs.mjs)', () => {
  it('has the section, tab and UI glyphs', () => {
    for (const n of ['esports', 'gym', 'venues', 'shop', 'hire', 'events', 'home', 'matches', 'ranks', 'account', 'today', 'checkin', 'passes', 'sections', 'eye', 'eye-off'] as IconName[]) {
      expect(NAMES).toContain(n);
    }
  });

  it('draws on the 256 grid', () => {
    expect(GLYPH_GRID).toBe(256);
  });

  it.each(NAMES)('%s has an outline that is one valid drawing', (name) => {
    expect(glyph(name).r).toMatch(DRAWING);
    const solid = glyph(name).f;
    if (solid !== undefined) {
      expect(solid).toMatch(DRAWING);
      expect(solid).not.toBe(glyph(name).r);
    }
  });

  it('gives every tab and section tile a solid drawing for its selected state', () => {
    for (const n of ['esports', 'gym', 'venues', 'shop', 'hire', 'events', 'home', 'matches', 'ranks', 'account', 'today', 'checkin', 'passes', 'sections'] as IconName[]) {
      expect(glyph(n).f).toBeDefined();
    }
  });

  it('stays small: the whole set is drawing data, not an icon package', () => {
    const bytes = NAMES.reduce((sum, n) => sum + glyph(n).r.length + (glyph(n).f?.length ?? 0), 0);
    expect(bytes).toBeLessThan(40_000);
  });

  it.each(NAMES)('%s renders, plain and active, without throwing', (name) => {
    act(() => {
      create(<Icon name={name} color="#0B7A4B" />);
      create(<Icon name={name} color="#FFFFFF" size={32} active accessibilityLabel={name} />);
    });
  });
});
